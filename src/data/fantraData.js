// Universal localization helper
export function getLocalizedValue(field, lang = 'id') {
  if (!field) return ''
  if (typeof field === 'string') return field
  if (typeof field === 'object') {
    if (field[lang]) return field[lang]
    if (field.en) return field.en
    if (field.id) return field.id
    const firstKey = Object.keys(field)[0]
    return field[firstKey] || ''
  }
  return String(field)
}

// Resolve a localized item where all multilingual objects are mapped to strings/arrays for the active language
export function getLocalizedItem(item, lang = 'id') {
  if (!item || typeof item !== 'object') return item

  const result = { ...item }

  for (const key of Object.keys(result)) {
    const val = result[key]
    if (val && typeof val === 'object' && !Array.isArray(val) && (val.id || val.en || val.ja || val.zh || val.ko || val.es || val.fr)) {
      result[key] = getLocalizedValue(val, lang)
    } else if (val && typeof val === 'object' && !Array.isArray(val) && (val.id && Array.isArray(val.id))) {
      // It's a localized array e.g. features: { id: [...], en: [...] }
      result[key] = val[lang] || val.en || val.id || []
    }
  }

  return result
}

